  function voiceLine(skin, kind) {
    const own = P.voice[skin];
    const base = P.voice.base;
    let v = own && own[kind] !== undefined ? own[kind] : base[kind];
    if (Array.isArray(v)) return pick(v);
    return v || '';
  }

  function touch(zone, count, aff) {
    const z = P.touch[zone] || P.touch.head;
    if (count === 1 && z.first) return { text: z.first, exp: z.exp, mood: z.mood };
    if (count === 3) return { text: P.touchCommon, exp: z.exp, mood: z.mood };
    const pool = (aff >= 60 && z.warm) ? z.warm : z.lines;
    return { text: pick(pool), exp: z.exp, mood: z.mood };
  }

  function studyLine(hour) {
    if (hour === 10) return pick(P.study.start);
    if (hour === 1) return pick(P.study.close);
    var pool = P.study.hourly[String(hour)] || P.study.hourly['15'];
    return pick(pool);
  }

